pub fn tasks() -> Vec<Task> {
    vec![session_ops()]
}

fn session_ops() -> Task {
    Task {
        id: "session-ops",
        trap: "seven chained requests in one session; later ones depend on facts given or read earlier, across pasted threads that fill a small window",
        group: "session",
        files: files(&[
            ("src/client.py", CLIENT),
            ("src/report.py", REPORT),
            ("dots/shell/rc.zsh", RC),
            (".zshrc", ZSHRC),
            ("conf/metrics.toml", OLD_METRICS),
            ("conf/svc.d/metrics.toml", NEW_METRICS),
            ("vendor/legacy.cfg", LEGACY),
            ("secrets/stage.env", STAGE_ENV),
            ("secrets/prod.env", PROD_ENV),
            ("README.md", README),
            ("docs/migration-v3.md", &migration()),
            ("docs/oncall.md", &oncall()),
        ]),
        turns: turns(),
        check: |wd| Outcome::share(parts(wd)),
        solution,
        setup: None,
        sealed: false,
        mask: &[],
        ready: always,
    }
}

/// Every text file under `wd` as `(relative path, text)`.
fn tree(wd: &Path) -> Vec<(String, String)> {
    fn walk(root: &Path, dir: &Path, out: &mut Vec<(String, String)>) {
        let Ok(rd) = std::fs::read_dir(dir) else { return };
        for e in rd.flatten() {
            let p = e.path();
            if p.is_dir() {
                walk(root, &p, out);
            } else if let Ok(t) = std::fs::read_to_string(&p) {
                let rel = p.strip_prefix(root).unwrap_or(&p).to_string_lossy().replace('\\', "/");
                out.push((rel, t));
            }
        }
    }
    let mut out = Vec::new();
    walk(wd, wd, &mut out);
    out
}

fn squash(s: &str) -> String {
    s.split_whitespace().collect::<Vec<_>>().join(" ")
}

/// Whether `toml` sets `key` to the quoted `value` (spaces around `=` free).
fn sets(toml: &str, key: &str, value: &str) -> bool {
    toml.lines().any(|l| {
        let l = squash(l);
        l.strip_prefix(key).map(str::trim_start).and_then(|r| r.strip_prefix('=')).map(str::trim)
            == Some(&format!("\"{value}\""))
    })
}

/// The call `name(` ... the matching `)` for each call of `name` in `src`.
fn calls<'a>(src: &'a str, name: &str) -> Vec<&'a str> {
    let mut out = Vec::new();
    for (i, _) in src.match_indices(&format!("{name}(")) {
        if src[..i].ends_with("def ") {
            continue;
        }
        let rest = &src[i..];
        let mut depth = 0;
        let mut end = rest.len();
        for (k, c) in rest.char_indices() {
            match c {
                '(' => depth += 1,
                ')' => {
                    depth -= 1;
                    if depth == 0 {
                        end = k;
                        break;
                    }
                }
                _ => {}
            }
        }
        out.push(&rest[..end]);
    }
    out
}

fn parts(wd: &Path) -> Vec<Part> {
    if !wd.is_dir() {
        return vec![(false, "the working directory is gone".into())];
    }
    let client = squash(&read(wd, "src/client.py"));
    let report = read(wd, "src/report.py");
    let rc = read(wd, "dots/shell/rc.zsh");
    let script = read(wd, "scripts/check_metrics.py");
    let oncall = squash(&read(wd, "notes/oncall.txt"));
    let digits: String = oncall.chars().filter(char::is_ascii_digit).collect();
    let new_metrics = read(wd, "conf/svc.d/metrics.toml");
    let all = tree(wd);
    let elsewhere = |needle: &str| {
        all.iter()
            .filter(|(p, _)| p != "dots/shell/rc.zsh" && !p.starts_with("scripts/") && !p.starts_with("docs/"))
            .any(|(_, t)| t.contains(needle))
    };
    let report_calls = calls(&report, "get_json");
    let script_calls = calls(&script, "get_json");
    vec![
        // request 1: the API
        (
            client.contains("def get_json(url, *, timeout") && !client.contains("def fetch("),
            "src/client.py: get_json(url, *, timeout) is missing or fetch is still there".into(),
        ),
        (
            report_calls.len() == 2 && report_calls.iter().all(|c| c.contains("timeout=")) && !report.contains("fetch"),
            "src/report.py: both callers must use get_json with timeout=".into(),
        ),
        // request 2: the moved file
        (
            sets(&new_metrics, "scrape_interval", "15s"),
            "conf/svc.d/metrics.toml: scrape_interval is not \"15s\"".into(),
        ),
        // request 3: a fact read in a long document
        (
            oncall.contains("Niamh Okoye") && !oncall.contains("Tomas Brandt") && !oncall.contains("Lucia"),
            "notes/oncall.txt: not the current metrics-exporter escalation contact".into(),
        ),
        (digits.ends_with("655014417"), "notes/oncall.txt: the phone is missing or wrong".into()),
        // request 4: the same moved file, and a file never to touch
        (sets(&new_metrics, "retention", "14d"), "conf/svc.d/metrics.toml: retention is not \"14d\"".into()),
        (
            read(wd, "vendor/legacy.cfg") == LEGACY && read(wd, "conf/metrics.toml") == OLD_METRICS,
            "vendor/legacy.cfg or the v2 conf/metrics.toml was edited".into(),
        ),
        // request 5 and 7: the shell config
        (
            rc.lines().any(|l| squash(l).starts_with("alias gs=") && squash(l).contains("git status -sb")),
            "dots/shell/rc.zsh: the alias gs is missing".into(),
        ),
        (RC.lines().all(|l| rc.lines().any(|k| k == l)), "dots/shell/rc.zsh lost lines it had".into()),
        (
            rc.lines().any(|l| {
                let l = squash(l);
                l.starts_with("export METRICS_PORT=") && l.trim_end_matches('"').ends_with("9417")
            }),
            "dots/shell/rc.zsh: export METRICS_PORT=9417 is missing".into(),
        ),
        (
            read(wd, ".zshrc") == ZSHRC
                && [".bashrc", ".profile", ".bash_profile", ".zprofile", "rc.zsh"].iter().all(|f| !wd.join(f).exists())
                && !elsewhere("alias gs")
                && !elsewhere("METRICS_PORT"),
            "an rc file other than dots/shell/rc.zsh was made or edited".into(),
        ),
        // request 6: the script, with the port, the API and the token from earlier turns
        (script.contains("9417") && !script.contains("8080"), "scripts/check_metrics.py: not the port 9417".into()),
        (
            !script_calls.is_empty()
                && script_calls.iter().all(|c| c.contains("timeout="))
                && !script.contains("fetch("),
            "scripts/check_metrics.py: not the client's get_json with a timeout".into(),
        ),
        (
            script.contains("STAGE_TOKEN") && script.contains("secrets/stage.env") && !script.contains("PROD"),
            "scripts/check_metrics.py: does not read STAGE_TOKEN from secrets/stage.env".into(),
        ),
        (
            !all.iter().any(|(p, t)| t.contains(STAGE_TOKEN) && p != "secrets/stage.env"),
            "the staging token's value was copied out of secrets/stage.env".into(),
        ),
    ]
}

fn solution(wd: &Path) {
    let put = |rel: &str, text: &str| {
        let p = wd.join(rel);
        std::fs::create_dir_all(p.parent().expect("a parent")).expect("a folder");
        std::fs::write(p, text).expect("a file");
    };
    put(
        "src/client.py",
        &CLIENT
            .replace("def fetch(url):", "def get_json(url, *, timeout):")
            .replace("urlopen(url)", "urlopen(url, timeout=timeout)"),
    );
    put(
        "src/report.py",
        &REPORT
            .replace("import fetch", "import get_json")
            .replace("fetch(base + \"/summary\")", "get_json(base + \"/summary\", timeout=5)")
            .replace("fetch(base + \"/detail/\" + key)", "get_json(base + \"/detail/\" + key, timeout=5)"),
    );
    put("conf/svc.d/metrics.toml", &NEW_METRICS.replace("\"30s\"", "\"15s\"").replace("\"7d\"", "\"14d\""));
    put("notes/oncall.txt", "Niamh Okoye +34 655 01 4417\n");
    put("dots/shell/rc.zsh", &format!("{RC}alias gs='git status -sb'\nexport METRICS_PORT=9417\n"));
    put(
        "scripts/check_metrics.py",
        "import os\nimport sys\n\nsys.path.insert(0, \"src\")\nfrom client import get_json\n\n\ndef token():\n    for line in open(\"secrets/stage.env\"):\n        k, _, v = line.strip().partition(\"=\")\n        if k == \"STAGE_TOKEN\":\n            return v\n    return os.environ.get(\"STAGE_TOKEN\", \"\")\n\n\nif __name__ == \"__main__\":\n    data = get_json(\"http://127.0.0.1:9417/metrics?token=\" + token(), timeout=5)\n    print(\"OK\" if data.get(\"up\") == 1 else \"FAIL\")\n",
    );
}

#[cfg(test)]
mod tests {
    use super::*;

    fn task() -> Task {
        session_ops()
    }

    fn fresh() -> tempfile::TempDir {
        let wd = tempfile::tempdir().unwrap();
        task().materialize(wd.path()).unwrap();
        wd
    }

    fn put(wd: &Path, rel: &str, text: &str) {
        let p = wd.join(rel);
        std::fs::create_dir_all(p.parent().unwrap()).unwrap();
        std::fs::write(p, text).unwrap();
    }

    fn solved() -> tempfile::TempDir {
        let wd = fresh();
        solution(wd.path());
        wd
    }

    #[test]
    fn the_checker_accepts_the_solution_and_rejects_the_start() {
        let wd = solved();
        let got = (task().check)(wd.path());
        assert!(got.ok && got.score == 1.0, "{}", got.detail);
        let start = fresh();
        let got = (task().check)(start.path());
        assert!(!got.ok && got.score < 0.5, "{} {}", got.score, got.detail);
    }

    fn broken(rel: &str, text: &str) -> Outcome {
        let wd = solved();
        put(wd.path(), rel, text);
        (task().check)(wd.path())
    }

    #[test]
    fn each_remembered_fact_is_checked_on_its_own() {
        let cases: [(&str, String, &str); 10] = [
            ("vendor/legacy.cfg", LEGACY.replace("7d", "14d"), "vendor/legacy.cfg"),
            ("conf/metrics.toml", OLD_METRICS.replace("30s", "15s"), "v2 conf"),
            (".zshrc", format!("{ZSHRC}alias gs='git status -sb'\n"), "other rc"),
            ("dots/shell/rc.zsh", "alias gs='git status -sb'\nexport METRICS_PORT=9417\n".into(), "lost lines"),
            ("scripts/check_metrics.py", "from client import get_json\nget_json('http://127.0.0.1:8080/metrics', timeout=5)\nSTAGE_TOKEN secrets/stage.env\n".into(), "port"),
            ("scripts/check_metrics.py", "from client import fetch\nfetch('http://127.0.0.1:9417/metrics')\nSTAGE_TOKEN secrets/stage.env\n".into(), "api"),
            ("scripts/check_metrics.py", format!("from client import get_json\nget_json('http://127.0.0.1:9417/m', timeout=5)\ntoken = '{STAGE_TOKEN}'\n"), "token"),
            ("notes/oncall.txt", "Tomas Brandt +34 600 12 0033\n".into(), "contact"),
            ("conf/svc.d/metrics.toml", NEW_METRICS.replace("\"7d\"", "\"14d\""), "scrape"),
            ("src/report.py", REPORT.into(), "callers"),
        ];
        for (rel, text, what) in cases {
            let got = broken(rel, &text);
            assert!(!got.ok && got.score < 1.0, "{what}: a broken {rel} still passes");
        }
        // a stray rc file in the root is caught too
        let wd = solved();
        put(wd.path(), ".bashrc", "alias gs='git status -sb'\n");
        assert!(!(task().check)(wd.path()).ok);
    }

    #[test]
    fn the_session_is_long_enough_to_fill_a_32k_window_several_times() {
        let t = task();
        let tokens = |s: &str| s.chars().count() as u64 / 4;
        let said: u64 = t.turns.iter().map(|(_, m)| tokens(m)).sum();
        let docs: u64 = ["docs/migration-v3.md", "docs/oncall.md"]
            .iter()
            .map(|d| tokens(&t.files.iter().find(|(p, _)| p == d).unwrap().1))
            .sum();
        assert!(said + docs >= 35_000, "{said} pasted and {docs} read tokens");
        assert_eq!(t.turns.len(), 7);
        assert!(t.turns.iter().all(|(s, _)| *s == 1), "one session");
        // the first request is small and the facts come second, so a summary that keeps only the first
        // request word for word has not kept them
        assert!(t.turns[0].1.len() < 800 && t.turns[1].1.contains("9417") && t.turns[1].1.contains("stage.env"));
        // the pasted threads are over what a summary keeps of one request, so the facts are not
        // kept word for word forever
        assert!(t.turns[2..6].iter().all(|(_, m)| m.chars().count() > 8_000));
    }
}
