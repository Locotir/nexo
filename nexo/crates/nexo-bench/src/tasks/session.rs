//! A long session of chained requests in one conversation, for a small context window.
//!
//! `session-ops`: seven requests to a small ops repo, sent one after another in one session. The
//! second states four things to remember (where the shell config lives, the metrics port, a file
//! never to touch, where the staging token is); a document read for the third request says where the
//! metrics settings moved; the first request changes an API. Later requests depend on those facts
//! without naming them ("add an alias to my shell config", "set the retention", "write the check script"),
//! and between them sit pasted threads big enough that a 32k window has to drop or summarise what came
//! before. With the whole history in view the facts are all there; the task measures what is left of
//! them once the window forces a compaction. Every part of the check reads files only, no model and no
//! toolchain.

use std::path::Path;

