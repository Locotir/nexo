//! CIL opcodes: names and operand shapes (ECMA-335, partition III).

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Arg {
    Nothing,
    I8,
    U8,
    I32,
    I64,
    F32,
    F64,
    /// A metadata token.
    Token,
    /// A user-string token (`ldstr`).
    Str,
    /// Branch with a 1-byte offset.
    Br1,
    /// Branch with a 4-byte offset.
    Br4,
    Switch,
    /// 1-byte local or argument index.
    Var1,
    /// 2-byte local or argument index.
    Var2,
}

use Arg::*;

