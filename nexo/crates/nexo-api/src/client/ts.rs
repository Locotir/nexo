pub fn render(m: &Model) -> String {
    let nm = names(m, FUNC_RESERVED, true);
    let mut out = String::new();
    out.push_str(&header(m, "//", &nm, "TypeScript, Node 18 or newer (global fetch), no imports."));
    out.push('\n');
    out.push_str(&slots(m));
    out.push_str(RUNTIME);
    for (o, n) in m.ops.iter().zip(&nm) {
        out.push('\n');
        out.push_str(&op(m, o, n));
    }
    out
}

fn slots(m: &Model) -> String {
    let mut s = String::from("\nconst NX_SLOTS: Record<string, NxSlot> = {\n");
    for sl in &m.slots {
        let (cookie, jar) = match &sl.kind {
            Kind::Csrf { cookie, jar, .. } => (cookie.clone(), jar.clone()),
            _ => (None, None),
        };
        let mut f = format!(
            "env: {}, kind: {}, name: {}, what: {}",
            lit(&sl.env),
            lit(sl.kind_word()),
            lit(&sl.target()),
            lit(&sl.what())
        );
        if let Some(c) = cookie {
            let _ = write!(f, ", cookie: {}", lit(&c));
        }
        if let Some(j) = jar {
            let _ = write!(f, ", jar: {}", lit(&j));
        }
        let _ = writeln!(s, "  {}: {{ {} }},", lit(&sl.label), f);
    }
    s.push_str("};\n");
    s
}

fn pascal(s: &str) -> String {
    let mut c = s.chars();
    match c.next() {
        Some(f) => f.to_ascii_uppercase().to_string() + c.as_str(),
        None => String::new(),
    }
}

fn op(m: &Model, o: &Op, n: &Names) -> String {
    let env = |label: &str| m.slot(label).map(|s| s.env.clone()).unwrap_or_default();
    let mut doc = String::from("/**\n");
    for l in notes(o, &env) {
        let _ = writeln!(doc, " * {l}");
    }
    doc.push_str(" */\n");
    let base = pascal(&n.func);
    let mut types = String::new();
    let resp = match &o.response {
        Some(sc) => {
            let name = format!("{base}Response");
            types.push_str(&decl(&name, sc));
            name
        }
        None => "unknown".to_string(),
    };
    let body_ty = match o.body.as_ref().and_then(|b| b.schema.as_ref()) {
        Some(sc) if o.gql.is_none() => {
            let name = format!("{base}Body");
            types.push_str(&decl(&name, sc));
            name
        }
        _ => "unknown".to_string(),
    };
    let vars_ty = match o.body.as_ref().and_then(|b| b.schema.as_ref()).and_then(|sc| sc.get("properties")) {
        Some(Value::Object(p)) if o.gql.is_some() => p
            .get("variables")
            .map(|v| {
                let name = format!("{base}Variables");
                types.push_str(&decl(&name, v));
                name
            })
            .unwrap_or_else(|| "Record<string, unknown>".to_string()),
        _ => "Record<string, unknown>".to_string(),
    };
    let ctype = o.body.as_ref().map(|b| b.mime.clone()).unwrap_or_else(|| "application/json".to_string());
    let form = o.body.as_ref().map(|b| b.form).unwrap_or(false);
    let mut out = types;
    let konst = format!("OP_{}", n.func);
    let auth: Vec<String> = o.auth.iter().map(|a| lit(a)).collect();
    let gql = match o.gql.as_ref().and_then(|g| g.operation.as_ref()) {
        Some(g) => format!(", gql: {}", lit(g)),
        None => String::new(),
    };
    let _ = writeln!(
        out,
        "const {konst}: NxOp = {{ id: {}, method: {}, origin: {}, path: {}, auth: [{}], ctype: {}, form: {}{gql} }};",
        lit(&o.id),
        lit(&o.method),
        lit(&o.origin),
        lit(&o.path),
        auth.join(", "),
        lit(&ctype),
        form
    );
    let args = arg_names(o, RESERVED);
    let mut params: Vec<String> = args.iter().map(|a| format!("{a}: string | number")).collect();
    let path_obj = if o.path_args.is_empty() {
        String::new()
    } else {
        let kv: Vec<String> = o.path_args.iter().zip(&args).map(|(k, a)| format!("{}: {a}", lit(k))).collect();
        format!("path: {{ {} }}, ", kv.join(", "))
    };
    let call = if o.gql.is_some() {
        params.push(format!("variables: {vars_ty} = {{}}"));
        params.push("query?: string".to_string());
        params.push("extensions?: Record<string, unknown>".to_string());
        format!("nxGql({konst}, variables, query, extensions)")
    } else {
        params.push("query: Record<string, unknown> = {}".to_string());
        let mut c = format!("{path_obj}query");
        if o.body.is_some() {
            params.push(format!("body?: {body_ty}"));
            c.push_str(", body");
        }
        format!("{{ {c} }}")
    };
    let ps = params.join(", ");
    out.push_str(&doc);
    let _ = writeln!(out, "export async function {}({ps}): Promise<{resp}> {{", n.func);
    let _ = writeln!(out, "  return (await nxSend({konst}, {call})).data;");
    out.push_str("}\n");
    if let (Some(pn), Some(p)) = (&n.pages, &o.pager) {
        let mut cfg = format!("style: {}", lit(p.style));
        if let Some(t) = &p.target {
            let (place, path) = place_path(t);
            let _ = write!(cfg, ", place: {}, path: {}", lit(place), json_arr(&path));
        }
        if let Some(x) = &p.next {
            let _ = write!(cfg, ", next: {}", json_arr(x));
        }
        if let Some(x) = &p.items {
            let _ = write!(cfg, ", items: {}", json_arr(x));
        }
        let mut ps2 = params.clone();
        ps2.push("limit = 1000".to_string());
        let first = call.clone();
        let _ = writeln!(out, "/** Every item of {}, page after page, up to `limit` items. */", n.func);
        let _ = writeln!(out, "export async function* {pn}({}): AsyncGenerator<any> {{", ps2.join(", "));
        let _ = writeln!(out, "  yield* nxPages({konst}, {first}, {{ {cfg} }}, limit);");
        out.push_str("}\n");
    }
    out
}

/// `export interface` for an object with fields, `export type` for anything else.
fn decl(name: &str, sc: &Value) -> String {
    let t = types_of(sc);
    if t == ["object"] {
        if let Some(Value::Object(props)) = sc.get("properties") {
            let req: Vec<&str> = sc
                .get("required")
                .and_then(|r| r.as_array())
                .map(|r| r.iter().filter_map(|x| x.as_str()).collect())
                .unwrap_or_default();
            let mut s = format!("export interface {name} {{\n");
            for (k, v) in props {
                if !safe(k) {
                    continue;
                }
                let opt = if req.contains(&k.as_str()) { "" } else { "?" };
                let _ = writeln!(s, "  {}{opt}: {};", lit(&clean(k)), ty(v, 0));
            }
            if sc.get("additionalProperties").is_some() {
                s.push_str("  [key: string]: unknown;\n");
            }
            s.push_str("}\n");
            return s;
        }
    }
    format!("export type {name} = {};\n", ty(sc, 0))
}

fn types_of(sc: &Value) -> Vec<String> {
    match sc.get("type") {
        Some(Value::String(t)) => vec![t.clone()],
        Some(Value::Array(a)) => a.iter().filter_map(|x| x.as_str().map(str::to_string)).collect(),
        _ => Vec::new(),
    }
}

/// A TypeScript type from a JSON Schema as `Shape::schema` writes it. Examples are never read.
fn ty(sc: &Value, depth: usize) -> String {
    let types = types_of(sc);
    if types.is_empty() || depth > 6 {
        return "unknown".to_string();
    }
    let mut parts: Vec<String> = Vec::new();
    for t in &types {
        let p = match t.as_str() {
            "boolean" => "boolean".to_string(),
            "number" | "integer" => "number".to_string(),
            "null" => "null".to_string(),
            "string" => string_ty(sc),
            "array" => {
                let inner = sc.get("items").map(|i| ty(i, depth + 1)).unwrap_or_else(|| "unknown".to_string());
                if inner.contains(' ') {
                    format!("Array<{inner}>")
                } else {
                    format!("{inner}[]")
                }
            }
            "object" => object_ty(sc, depth),
            _ => "unknown".to_string(),
        };
        if !parts.contains(&p) {
            parts.push(p);
        }
    }
    parts.join(" | ")
}

fn string_ty(sc: &Value) -> String {
    if let Some(Value::Array(e)) = sc.get("enum") {
        let strs: Vec<&str> = e.iter().filter_map(|x| x.as_str()).collect();
        if !strs.is_empty() && strs.iter().all(|s| safe(s)) {
            return strs.iter().map(|s| lit(s)).collect::<Vec<_>>().join(" | ");
        }
    }
    "string".to_string()
}

fn object_ty(sc: &Value, depth: usize) -> String {
    let mut members: Vec<String> = Vec::new();
    if let Some(Value::Object(props)) = sc.get("properties") {
        let req: Vec<&str> = sc
            .get("required")
            .and_then(|r| r.as_array())
            .map(|r| r.iter().filter_map(|x| x.as_str()).collect())
            .unwrap_or_default();
        for (k, v) in props {
            if !safe(k) {
                continue;
            }
            let opt = if req.contains(&k.as_str()) { "" } else { "?" };
            members.push(format!("{}{opt}: {}", lit(&clean(k)), ty(v, depth + 1)));
        }
    }
    match sc.get("additionalProperties") {
        Some(d) if members.is_empty() => members.push(format!("[key: string]: {}", ty(d, depth + 1))),
        Some(_) => members.push("[key: string]: unknown".to_string()),
        None if members.is_empty() => members.push("[key: string]: unknown".to_string()),
        None => {}
    }
    format!("{{ {} }}", members.join("; "))
}
