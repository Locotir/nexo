//! The shell client: POSIX `sh` and `curl`, one function per operation. Paging is left to the caller.
//!
//! A credential never goes to `curl` as an argument (a process list would show it): the request is a `curl -K -` config
//! read from standard input.

use super::{arg_names, header, lit, names, notes, shq, template_names, Kind, Model, Names, Op};
use std::fmt::Write;

/// Words and commands a function may not shadow.
pub(super) const RESERVED: &[&str] = &[
    "if", "then", "else", "elif", "fi", "case", "esac", "for", "while", "until", "do", "done", "in", "function",
    "select", "time", "coproc", "cd", "test", "echo", "read", "exit", "set", "shift", "eval", "exec", "export",
    "return", "trap", "unset", "wait", "printf", "curl", "sed", "awk", "cat", "rm", "sleep", "mktemp", "tr", "od",
    "grep", "true", "false", "type", "command", "alias", "break", "continue", "local", "kill", "ls", "mv", "cp", "env",
    "sh", "base64", "head", "cut", "sort", "date", "pwd", "umask", "getopts", "hash", "readonly", "times", "ulimit",
];

const RUNTIME: &str = r####"
NEXO_API_UA='nexo-api-client/1 (generated by nexo)'

# Percent-encodes every byte of $1.
_nx_enc() { printf '%s' "$1" | od -An -v -tx1 | tr -d ' \n' | sed 's/../%&/g'; }
# Escapes $1 for a curl config string.
_nx_cq() { printf '%s' "$1" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g'; }
# Escapes $1 for a JSON string.
_nx_jstr() {
  _nx_tab=$(printf '\t')
  printf '%s' "$1" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g' -e "s/$_nx_tab/\\\\t/g" | awk 'NR > 1 { printf "\\n" } { printf "%s", $0 }'
}
# The value of cookie $2 in the cookie string $1.
_nx_cookie() { printf '%s' "$1" | tr ';' '\n' | awk -F= -v n="$2" '{ sub(/^ +/, ""); if ($1 == n) { sub(/^[^=]*=/, ""); print; exit } }'; }
# Seconds to wait after a 429, from the headers file $1: Retry-After in seconds, one by default, 30 at most.
_nx_wait() {
  _nx_w=$(grep -i '^retry-after:' "$1" 2>/dev/null | tr -d '\r' | awk '{ print $2; exit }')
  case $_nx_w in '' | *[!0-9]*) _nx_w=1 ;; esac
  [ "$_nx_w" -le 30 ] || _nx_w=30
  printf '%s' "$_nx_w"
}
_nx_env() { eval "printf '%s' \"\${$1:-}\""; }
_nx_hdr() { _nx_cfg="$_nx_cfg
header = \"$(_nx_cq "$1: $2")\""; }
"####;

const SLOT_TAIL: &str = r####"
  _s_v=$(_nx_env "$_s_env")
  case $_s_kind in
    cookie)
      [ -z "$_s_v" ] || _nx_hdr cookie "$_s_v"
      return 0 ;;
    csrf)
      if [ -z "$_s_v" ] && [ -n "$_s_cookie" ] && [ -n "$_s_jar" ]; then
        _s_v=$(_nx_cookie "$(_nx_env "$_s_jar")" "$_s_cookie")
      fi ;;
  esac
  if [ -z "$_s_v" ]; then
    printf '%s\n' "$2: set the environment variable $_s_env ($_s_what)" >&2
    return 1
  fi
  case $_s_kind in
    bearer)
      case $_s_v in [Bb]earer\ *) ;; *) _s_v="Bearer $_s_v" ;; esac
      _nx_hdr "$_s_name" "$_s_v" ;;
    basic)
      case $_s_v in [Bb]asic\ *) ;; *) _s_v="Basic $(printf '%s' "$_s_v" | base64 | tr -d '\n')" ;; esac
      _nx_hdr "$_s_name" "$_s_v" ;;
    query) _nx_qa="$_nx_qa&$(_nx_enc "$_s_name")=$(_nx_enc "$_s_v")" ;;
    *) _nx_hdr "$_s_name" "$_s_v" ;;
  esac
}

# _nx_call ID METHOD ORIGIN PATH LABELS CONTENT-TYPE [name=value]... [--body JSON | --body-file FILE]
_nx_call() {
  _c_id=$1; _c_method=$2; _c_origin=$3; _c_path=$4; _c_labels=$5; _c_ctype=$6
  shift 6
  _c_q=; _c_body=; _c_bfile=
  while [ $# -gt 0 ]; do
    case $1 in
      --body) [ $# -ge 2 ] || { printf '%s\n' "$_c_id: --body needs a value" >&2; return 2; }
        _c_body=$2; shift 2 ;;
      --body=*) _c_body=${1#--body=}; shift ;;
      --body-file) [ $# -ge 2 ] || { printf '%s\n' "$_c_id: --body-file needs a path" >&2; return 2; }
        _c_bfile=$2; shift 2 ;;
      *=*) _c_q="$_c_q&$(_nx_enc "${1%%=*}")=$(_nx_enc "${1#*=}")"; shift ;;
      *) printf '%s\n' "$_c_id: unexpected argument $1 (use name=value, --body JSON or --body-file FILE)" >&2; return 2 ;;
    esac
  done
  _nx_cfg=; _nx_qa=
  for _c_l in $_c_labels; do
    _nx_slot "$_c_l" "$_c_id" || return 1
  done
  _c_all="$_c_q$_nx_qa"
  _c_url="$_c_origin$_c_path"
  [ -z "$_c_all" ] || _c_url="$_c_url?${_c_all#&}"
  _c_tmp=
  if [ -n "$_c_body" ]; then
    _c_tmp=$(mktemp) || return 1
    printf '%s' "$_c_body" > "$_c_tmp"
    _c_bfile=$_c_tmp
  fi
  _c_hdr=$(mktemp) || return 1
  _c_out=$(mktemp) || return 1
  _c_try=0
  while :; do
    _c_code=$({
      printf 'url = "%s"\n' "$(_nx_cq "$_c_url")"
      printf 'request = "%s"\n' "$_c_method"
      printf 'header = "user-agent: %s"\n' "$NEXO_API_UA"
      printf 'header = "accept: application/json"\n'
      if [ -n "$_c_bfile" ] && [ "$_c_method" != GET ] && [ "$_c_method" != HEAD ]; then
        printf 'header = "content-type: %s"\n' "$(_nx_cq "$_c_ctype")"
        printf 'data-binary = "@%s"\n' "$(_nx_cq "$_c_bfile")"
      fi
      printf '%s\n' "$_nx_cfg"
    } | curl -sS --max-time 30 -K - -D "$_c_hdr" -o "$_c_out" -w '%{http_code}') || _c_code=
    if [ "$_c_code" = 429 ] && [ "$_c_try" -eq 0 ]; then
      _c_try=1
      sleep "$(_nx_wait "$_c_hdr")"
      continue
    fi
    break
  done
  _c_rc=0
  case $_c_code in
    2??) cat "$_c_out"; printf '\n' ;;
    '' | 000) printf '%s\n' "$_c_id: the request failed" >&2; _c_rc=1 ;;
    *) printf '%s\n' "$_c_id: HTTP $_c_code" >&2; head -c 300 "$_c_out" >&2; printf '\n' >&2; _c_rc=22 ;;
  esac
  rm -f "$_c_hdr" "$_c_out" ${_c_tmp:+"$_c_tmp"}
  return "$_c_rc"
}
"####;

pub fn render(m: &Model) -> String {
    let nm = names(m, RESERVED, false);
    let mut out = String::from("#!/bin/sh\n");
    out.push_str(&header(
        m,
        "#",
        &nm,
        "POSIX sh and curl. Source it (. ./FILE) and call a function, or use `sh -c '. ./FILE; NAME ARGS'`.",
    ));
    out.push_str(RUNTIME);
    out.push_str(&slots(m));
    out.push_str(SLOT_TAIL);
    for (o, n) in m.ops.iter().zip(&nm) {
        out.push('\n');
        out.push_str(&op(m, o, n));
    }
    out
}

/// A label as one word, as `_nx_call` passes it around.
fn key(label: &str) -> String {
    label.chars().map(|c| if c.is_whitespace() { '_' } else { c }).collect()
}

fn slots(m: &Model) -> String {
    let mut s = String::from("\n# One case per auth scheme: the variable it is read from and where the value goes.\n_nx_slot() {\n  case $1 in\n");
    for sl in &m.slots {
        let (cookie, jar) = match &sl.kind {
            Kind::Csrf { cookie, jar, .. } => (cookie.clone().unwrap_or_default(), jar.clone().unwrap_or_default()),
            _ => (String::new(), String::new()),
        };
        let _ = writeln!(
            s,
            "    {}) _s_env={}; _s_kind={}; _s_name={}; _s_what={}; _s_cookie={}; _s_jar={} ;;",
            shq(&key(&sl.label)),
            shq(&sl.env),
            shq(sl.kind_word()),
            shq(&sl.target()),
            shq(&sl.what()),
            shq(&cookie),
            shq(&jar)
        );
    }
    s.push_str("    *) printf '%s\\n' \"$2: unknown auth slot $1\" >&2; return 1 ;;\n  esac");
    s
}

/// The shell text that builds an operation's path from its arguments `$1`, `$2`, ...
fn path_expr(o: &Op) -> String {
    let order = template_names(&o.path);
    let mut out = String::new();
    let mut rest = o.path.as_str();
    let mut lit_part = String::new();
    while let Some(a) = rest.find('{') {
        let Some(len) = rest[a..].find('}') else { break };
        lit_part.push_str(&rest[..a]);
        if !lit_part.is_empty() {
            out.push_str(&shq(&lit_part));
            lit_part.clear();
        }
        let name = &rest[a + 1..a + len];
        let idx = order.iter().position(|n| n == name).unwrap_or(0) + 1;
        let _ = write!(out, "\"$(_nx_enc \"${idx}\")\"");
        rest = &rest[a + len + 1..];
    }
    lit_part.push_str(rest);
    if !lit_part.is_empty() {
        out.push_str(&shq(&lit_part));
    }
    if out.is_empty() {
        "''".to_string()
    } else {
        out
    }
}

fn op(m: &Model, o: &Op, n: &Names) -> String {
    let env = |label: &str| m.slot(label).map(|s| s.env.clone()).unwrap_or_default();
    let mut out = String::new();
    for l in notes(o, &env) {
        let _ = writeln!(out, "# {l}");
    }
    if let Some(p) = &o.pager {
        let _ = writeln!(out, "# Paging ({}) is left out: call it again with the next page's value yourself.", p.text);
    }
    let labels: Vec<String> = o.auth.iter().map(|a| key(a)).collect();
    let ctype = o.body.as_ref().map(|b| b.mime.clone()).unwrap_or_else(|| "application/json".to_string());
    let args = arg_names(o, &[]);
    let upper: Vec<String> = args.iter().map(|a| a.to_ascii_uppercase()).collect();
    let _ = writeln!(out, "{}() {{", n.func);
    let common = format!(
        "{} {} {} \"$_p\" {} {}",
        shq(&o.id),
        shq(&o.method),
        shq(&o.origin),
        shq(&labels.join(" ")),
        shq(&ctype)
    );
    if let Some(g) = &o.gql {
        let name = g.operation.clone().unwrap_or_default();
        let usage = "usage: NAME VARIABLES_JSON [QUERY_TEXT] [EXTENSIONS_JSON]";
        let _ = writeln!(
            out,
            "  [ $# -ge 1 ] || {{ printf '%s\\n' {} >&2; return 2; }}",
            shq(&usage.replace("NAME", &n.func))
        );
        let _ = writeln!(out, "  _p={}", shq(&o.path));
        let _ = writeln!(out, "  if [ -z \"${{2:-}}\" ] && [ -z \"${{3:-}}\" ]; then");
        let _ = writeln!(
            out,
            "    printf '%s\\n' {} >&2; return 2",
            shq(&format!("{}: pass the GraphQL query text, or extensions with the persisted-query hash", n.func))
        );
        out.push_str("  fi\n");
        if o.method == "GET" {
            let _ = writeln!(out, "  set -- \"variables=$1\" \"query=${{2:-}}\" \"extensions=${{3:-}}\"");
            if !name.is_empty() {
                let _ = writeln!(out, "  set -- {} \"$@\"", shq(&format!("operationName={name}")));
            }
            let _ = writeln!(out, "  _nx_call {common} \"$@\"");
        } else {
            out.push_str("  _b='{'\n");
            if !name.is_empty() {
                let _ = writeln!(out, "  _b=\"$_b\"{}", shq(&format!("\"operationName\":{},", lit(&name))));
            }
            out.push_str("  [ -z \"${2:-}\" ] || _b=\"$_b\\\"query\\\":\\\"$(_nx_jstr \"$2\")\\\",\"\n");
            out.push_str("  [ -z \"${3:-}\" ] || _b=\"$_b\\\"extensions\\\":$3,\"\n");
            out.push_str("  _b=\"$_b\\\"variables\\\":$1}\"\n");
            let _ = writeln!(out, "  _nx_call {common} --body \"$_b\"");
        }
        out.push_str("}\n");
        return out;
    }
    let count = args.len();
    if count > 0 {
        let usage = format!(
            "usage: {} {} [name=value]...{}",
            n.func,
            upper.join(" "),
            if o.body.is_some() { " [--body JSON | --body-file FILE]" } else { "" }
        );
        let _ = writeln!(out, "  [ $# -ge {count} ] || {{ printf '%s\\n' {} >&2; return 2; }}", shq(&usage));
    }
    let _ = writeln!(out, "  _p={}", path_expr(o));
    if count > 0 {
        let _ = writeln!(out, "  shift {count}");
    }
    let _ = writeln!(out, "  _nx_call {common} \"$@\"");
    out.push_str("}\n");
    out
}
