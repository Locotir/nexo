pub fn render(m: &Model) -> String {
    let nm = names(m, RESERVED, true);
    let mut out = String::new();
    out.push_str(&header(m, "#", &nm, "Python 3.9 or newer, standard library only."));
    out.push_str(RUNTIME);
    out.push_str(&slots(m));
    for (o, n) in m.ops.iter().zip(&nm) {
        out.push_str("\n\n");
        out.push_str(&op(m, o, n));
    }
    out
}

fn slots(m: &Model) -> String {
    let mut s = String::from("\n\nNX_SLOTS = {\n");
    for sl in &m.slots {
        let (cookie, jar) = match &sl.kind {
            Kind::Csrf { cookie, jar, .. } => (cookie.clone(), jar.clone()),
            _ => (None, None),
        };
        let mut f = format!(
            "\"env\": {}, \"kind\": {}, \"name\": {}, \"what\": {}",
            lit(&sl.env),
            lit(sl.kind_word()),
            lit(&sl.target()),
            lit(&sl.what())
        );
        if let Some(c) = cookie {
            let _ = write!(f, ", \"cookie\": {}", lit(&c));
        }
        if let Some(j) = jar {
            let _ = write!(f, ", \"jar\": {}", lit(&j));
        }
        let _ = writeln!(s, "    {}: {{{}}},", lit(&sl.label), f);
    }
    s.push_str("}\n");
    s
}

fn op(m: &Model, o: &Op, n: &Names) -> String {
    let env = |label: &str| m.slot(label).map(|s| s.env.clone()).unwrap_or_default();
    let konst = format!("_OP_{}", n.func);
    let auth: Vec<String> = o.auth.iter().map(|a| lit(a)).collect();
    let ctype = o.body.as_ref().map(|b| b.mime.clone()).unwrap_or_else(|| "application/json".to_string());
    let form = o.body.as_ref().map(|b| b.form).unwrap_or(false);
    let mut out = format!(
        "{konst} = {{\"id\": {}, \"method\": {}, \"origin\": {}, \"path\": {}, \"auth\": [{}], \"ctype\": {}, \"form\": {}",
        lit(&o.id),
        lit(&o.method),
        lit(&o.origin),
        lit(&o.path),
        auth.join(", "),
        lit(&ctype),
        if form { "True" } else { "False" }
    );
    if let Some(g) = o.gql.as_ref().and_then(|g| g.operation.as_ref()) {
        let _ = write!(out, ", \"gql\": {}", lit(g));
    }
    out.push_str("}\n");
    for l in notes(o, &env) {
        let _ = writeln!(out, "# {l}");
    }
    let args = arg_names(o, ARG_RESERVED);
    let mut params: Vec<String> = args.clone();
    let path_obj = if o.path_args.is_empty() {
        "None".to_string()
    } else {
        let kv: Vec<String> = o.path_args.iter().zip(&args).map(|(k, a)| format!("{}: {a}", lit(k))).collect();
        format!("{{{}}}", kv.join(", "))
    };
    let kwargs = if o.gql.is_some() {
        params.push("variables=None".to_string());
        params.push("query=None".to_string());
        params.push("extensions=None".to_string());
        format!("**_nx_gql({konst}, variables, query, extensions)")
    } else {
        params.push("query=None".to_string());
        let mut c = format!("path={path_obj}, query=query");
        if o.body.is_some() {
            params.push("body=None".to_string());
            c.push_str(", body=body");
        }
        c
    };
    let _ = writeln!(out, "def {}({}):", n.func, params.join(", "));
    let _ = writeln!(out, "    return _nx_send({konst}, {kwargs})[0]");
    if let (Some(pn), Some(p)) = (&n.pages, &o.pager) {
        let mut cfg = format!("\"style\": {}", lit(p.style));
        if let Some(t) = &p.target {
            let (place, path) = place_path(t);
            let _ = write!(cfg, ", \"place\": {}, \"path\": {}", lit(place), json_arr(&path));
        }
        if let Some(x) = &p.next {
            let _ = write!(cfg, ", \"next\": {}", json_arr(x));
        }
        if let Some(x) = &p.items {
            let _ = write!(cfg, ", \"items\": {}", json_arr(x));
        }
        let mut ps = params.clone();
        ps.push("limit=1000".to_string());
        let first = if o.gql.is_some() {
            format!("_nx_gql({konst}, variables, query, extensions)")
        } else {
            let mut c = format!("{{\"path\": {path_obj}, \"query\": query");
            if o.body.is_some() {
                c.push_str(", \"body\": body");
            }
            c.push('}');
            c
        };
        let _ = writeln!(out, "\n\n# Every item of {}, page after page, up to `limit` items.", n.func);
        let _ = writeln!(out, "def {pn}({}):", ps.join(", "));
        let _ = writeln!(out, "    yield from _nx_pages({konst}, {first}, {{{cfg}}}, limit)");
    }
    out
}
